"""Safe, Reversible Cleanup Utility for Synthetic Demo Data.

Identifies and cleanly removes historical synthetic records generated by
`agents/run_demo.py` (support_agent, finance_agent, devops_agent, research_agent)
while strictly preserving user-registered agents and legitimate tenant data.

Usage:
    # 1. Inspect without modifying (Dry run):
    python scripts/cleanup_synthetic_data.py --inspect

    # 2. Safely clean with automated JSON backup:
    python scripts/cleanup_synthetic_data.py --execute --backup
"""

import argparse
import asyncio
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Add backend/src to path and ensure backend/.env is loaded if present
backend_dir = Path(__file__).resolve().parent.parent / "backend"
backend_src = backend_dir / "src"
sys.path.insert(0, str(backend_src))

backend_env = backend_dir / ".env"
if backend_env.exists():
    import dotenv
    dotenv.load_dotenv(backend_env)

from sqlalchemy import delete, select
from agent_security.db.session import close_db, get_session_maker, init_db
from agent_security.db.models import (
    AgentModel,
    AgentCredentialModel,
    AgentSessionModel,
    RuntimeActionModel,
    ApprovalRequestModel,
    AuditEventModel,
    ExecutionAuthorizationModel,
)

SYNTHETIC_AGENT_IDS = {
    "support_agent",
    "finance_agent",
    "devops_agent",
    "research_agent",
}


async def inspect_synthetic_records():
    await init_db()
    session_maker = get_session_maker()
    async with session_maker() as db:
        agent_stmt = select(AgentModel).where(AgentModel.id.in_(SYNTHETIC_AGENT_IDS))
        synthetic_agents = (await db.execute(agent_stmt)).scalars().all()

        action_stmt = select(RuntimeActionModel).where(RuntimeActionModel.agent_id.in_(SYNTHETIC_AGENT_IDS))
        synthetic_actions = (await db.execute(action_stmt)).scalars().all()

        session_stmt = select(AgentSessionModel).where(AgentSessionModel.agent_id.in_(SYNTHETIC_AGENT_IDS))
        synthetic_sessions = (await db.execute(session_stmt)).scalars().all()

        cred_stmt = select(AgentCredentialModel).where(AgentCredentialModel.agent_id.in_(SYNTHETIC_AGENT_IDS))
        synthetic_creds = (await db.execute(cred_stmt)).scalars().all()

        all_agents_stmt = select(AgentModel)
        all_agents = (await db.execute(all_agents_stmt)).scalars().all()
        user_agents = [a for a in all_agents if a.id not in SYNTHETIC_AGENT_IDS]

        print("\n" + "=" * 65)
        print("SYNTHETIC DEMO DATA AUDIT")
        print("=" * 65)
        print(f"Total Agents in DB          : {len(all_agents)}")
        print(f"Verified Synthetic Demo Agents: {len(synthetic_agents)} ({', '.join(a.id for a in synthetic_agents)})")
        print(f"User-Created Custom Agents  : {len(user_agents)} ({', '.join(a.id for a in user_agents) if user_agents else 'None'})")
        print(f"Synthetic Runtime Actions   : {len(synthetic_actions)}")
        print(f"Synthetic Runtime Sessions  : {len(synthetic_sessions)}")
        print(f"Synthetic Credentials       : {len(synthetic_creds)}")
        print("=" * 65)

        return {
            "synthetic_agents": [a.id for a in synthetic_agents],
            "synthetic_actions_count": len(synthetic_actions),
            "user_agents": [a.id for a in user_agents],
        }


async def execute_cleanup(create_backup: bool = True):
    await init_db()
    session_maker = get_session_maker()
    backup_path = Path(__file__).resolve().parent / f"backup_synthetic_data_{int(datetime.now(timezone.utc).timestamp())}.json"

    async with session_maker() as db:
        # 1. Fetch synthetic agents
        agent_stmt = select(AgentModel).where(AgentModel.id.in_(SYNTHETIC_AGENT_IDS))
        agents = (await db.execute(agent_stmt)).scalars().all()

        if not agents:
            print("[✓] No synthetic demo agents found in the database. Cleanup not needed.")
            return

        action_stmt = select(RuntimeActionModel).where(RuntimeActionModel.agent_id.in_(SYNTHETIC_AGENT_IDS))
        actions = (await db.execute(action_stmt)).scalars().all()
        action_ids = [a.id for a in actions]

        session_stmt = select(AgentSessionModel).where(AgentSessionModel.agent_id.in_(SYNTHETIC_AGENT_IDS))
        sessions = (await db.execute(session_stmt)).scalars().all()

        cred_stmt = select(AgentCredentialModel).where(AgentCredentialModel.agent_id.in_(SYNTHETIC_AGENT_IDS))
        creds = (await db.execute(cred_stmt)).scalars().all()

        if create_backup:
            backup_data = {
                "created_at": datetime.now(timezone.utc).isoformat(),
                "agents": [{"id": a.id, "name": a.name, "org": a.organization_id} for a in agents],
                "actions_count": len(actions),
                "sessions_count": len(sessions),
                "credentials_count": len(creds),
            }
            with open(backup_path, "w", encoding="utf-8") as f:
                json.dump(backup_data, f, indent=2)
            print(f"[+] Reversible backup saved to: {backup_path}")

        # 2. Safely delete associated executions, approvals, actions, sessions, credentials, agents
        if action_ids:
            await db.execute(delete(ExecutionAuthorizationModel).where(ExecutionAuthorizationModel.action_id.in_(action_ids)))
            await db.execute(delete(ApprovalRequestModel).where(ApprovalRequestModel.action_id.in_(action_ids)))
            await db.execute(delete(RuntimeActionModel).where(RuntimeActionModel.id.in_(action_ids)))

        await db.execute(delete(AgentSessionModel).where(AgentSessionModel.agent_id.in_(SYNTHETIC_AGENT_IDS)))
        await db.execute(delete(AgentCredentialModel).where(AgentCredentialModel.agent_id.in_(SYNTHETIC_AGENT_IDS)))
        await db.execute(delete(AgentModel).where(AgentModel.id.in_(SYNTHETIC_AGENT_IDS)))

        await db.commit()
        print(f"[✓] Successfully removed {len(agents)} synthetic agents and {len(actions)} synthetic actions.")
        print("[✓] Any user-created agents and custom data remain untouched.")


def main():
    parser = argparse.ArgumentParser(description="Synthetic Demo Data Audit & Cleanup Tool")
    parser.add_argument("--inspect", action="store_true", help="Inspect and count synthetic records without deleting")
    parser.add_argument("--execute", action="store_true", help="Execute safe, reversible deletion of synthetic demo data")
    parser.add_argument("--no-backup", action="store_true", help="Skip creating JSON backup file before cleanup")
    args = parser.parse_args()

    try:
        if args.execute:
            asyncio.run(execute_cleanup(create_backup=not args.no_backup))
        else:
            asyncio.run(inspect_synthetic_records())
    finally:
        asyncio.run(close_db())


if __name__ == "__main__":
    main()
